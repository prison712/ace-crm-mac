export type I18nKey = keyof (typeof I18N)["zh"];

let currentLang: UiLang = detectLang();

function detectLang(): UiLang {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === "zh" || saved === "en") return saved;
  const nav = (navigator.language || "en").toLowerCase();
  return nav.startsWith("zh") ? "zh" : "en";
}

export function getLang(): UiLang {
  return currentLang;
}

export function setLang(lang: UiLang): void {
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
}

export function t(
  key: I18nKey,
  vars?: Record<string, string | number>,
  lang: UiLang = currentLang,
): string {
  const raw = I18N[lang][key] ?? I18N.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : `{${name}}`,
  );
}

/** Subscribe to language changes (for React) */
const listeners = new Set<() => void>();

export function subscribeLang(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function setLangAndNotify(lang: UiLang): void {
  setLang(lang);
  listeners.forEach((fn) => fn());
}

// init document lang on load
setLang(currentLang);
